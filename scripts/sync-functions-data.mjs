// Writes supabase/functions/_shared/generated.js: the parts of the site's data the Edge Functions need (business details, the confirmation email's
// wording, the form's choices and the assistant's instructions), so the functions use the same words as the website. Edit the data files, run
//   npm run functions:sync
// and redeploy the functions (supabase functions deploy). Run it with: node --no-warnings --import ./scripts/alias.mjs scripts/sync-functions-data.mjs
import { writeFileSync } from 'node:fs';
import { BUSINESS, LEADS_EMAIL, PHONE, SITE_URL, TEL } from '../data/site.js';
import { AUTO_REPLY } from '../data/autoReply.js';
import { FOUND_US_OPTIONS, ROOF_TYPES, SERVICE_OPTIONS, VISIT_TIMES } from '../data/estimateOptions.js';
import { SYSTEM_PROMPT } from '../data/assistant.js';
import { formatDate } from '../lib/dates.js';
import { hoursText } from '../lib/hours.js';

const generated = {
  SITE: {
    name: BUSINESS.name,
    legalName: BUSINESS.legalName,
    siteUrl: SITE_URL,
    phone: PHONE,
    tel: TEL,
    leadsEmail: LEADS_EMAIL,
    license: BUSINESS.license,
    licenseSince: formatDate(BUSINESS.licenseSince),
    hoursText: hoursText(BUSINESS.hours),
  },
  AUTO_REPLY,
  OPTIONS: { SERVICE_OPTIONS, ROOF_TYPES, VISIT_TIMES, FOUND_US_OPTIONS },
  SYSTEM_PROMPT,
};

const file = new URL('../supabase/functions/_shared/generated.js', import.meta.url);
const body = Object.entries(generated).map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)};\n`).join('\n');
writeFileSync(file, `// GENERATED by scripts/sync-functions-data.mjs from the site's data files: do not edit by hand (run npm run functions:sync).\n\n${body}`);
console.log('wrote supabase/functions/_shared/generated.js');
